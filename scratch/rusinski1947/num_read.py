def main():
    at = json.load(open(os.path.join(OCR, 'annex_table.json'),
                        encoding='utf-8'))
    ims = {}
    panels = []
    for n, num, col in CELLS:
        if n not in ims:
            with open(os.path.join(SRC, 'tom5_%s.tif' % n), 'rb') as fh:
                im = Image.open(io.BytesIO(fh.read())).convert('L')
            im.load()
            ims[n] = im
        im = ims[n]
        rules = RULES[n]
        y0, y1 = at[n]['rows'][str(num)]['y']
        x0, x1 = rules[col - 1] + 4, rules[col] - 4
        c = im.crop((x0, y0, x1, y1))
        c = c.resize((c.size[0] * 6, c.size[1] * 6), Image.LANCZOS)
        panels.append(('%s r%d c%d' % (n, num, col), c))
    per = 8
    for si in range(0, len(panels), per):
        chunk = panels[si:si + per]
        W = max(p.size[0] for _, p in chunk) + 170
        H = sum(p.size[1] + 10 for _, p in chunk) + 10
        out = Image.new('L', (W, H), 255)
        d = ImageDraw.Draw(out)
        yy = 5
        for tag, p in chunk:
            out.paste(p, (160, yy))
            d.text((5, yy + p.size[1] // 2), tag, fill=0)
            yy += p.size[1] + 10
        out.save(r'C:\Users\Tersnaus\AppData\Local\Temp\opencode\numrd_%02d.png'
                 % (si // per))
        print('numrd_%02d.png' % (si // per), out.size)


if __name__ == '__main__':
    main()
