"""Fit a map's control points and write the Allmaps georeference annotation.

    python pipeline/maps/georef.py <key> [--order 1|2]

Control points: maps/<key>/georef.yml's gcps, plus every label of
maps/<key>/labels.yml with a `point` whose gazetteer place is `surveyed`
(lat/lon).  Writes the `fit:` block of georef.yml, maps/<key>/positions.yml
(when there are labels) and MAPS_REPO/<key>/georef.json.
"""
import argparse
import json
import math
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from common import (MAPS_REPO, TILE_BASE, die, dump_yaml, header_of, load_gazetteer,
                    load_map, map_dir, read_yaml, utf8_stdout)

POSITIONS_HEADER = """\
# GENERATED by pipeline/maps/georef.py from maps/{key}/labels.yml and the fit
# in georef.yml; do not edit. The ground position of every marked point,
# from the map's fit (rms_m is the fit's root-mean-square error in metres).
"""


def design(xy, order):
    x, y = xy[:, 0], xy[:, 1]
    cols = [np.ones_like(x), x, y]
    if order == 2:
        cols += [x * x, x * y, y * y]
    return np.column_stack(cols)


def fit(src, dst, order):
    coef, *_ = np.linalg.lstsq(design(src, order), dst, rcond=None)
    return coef


def apply(coef, xy, order):
    return design(np.atleast_2d(xy), order) @ coef


def main():
    utf8_stdout()
    ap = argparse.ArgumentParser()
    ap.add_argument("key")
    ap.add_argument("--order", type=int, default=1, choices=[1, 2])
    a = ap.parse_args()
    key, order = a.key, a.order
    m = load_map(key, check_file=False)
    gpath = map_dir(key) / "georef.yml"
    if not gpath.is_file():
        die(f"{gpath} is missing; run mapwarper.py first")
    geo = read_yaml(gpath)
    pts = [{"id": g["id"], "x": g["x"], "y": g["y"], "lon": g["lon"], "lat": g["lat"]}
           for g in geo.get("gcps", [])]

    lpath = map_dir(key) / "labels.yml"
    labels = []
    if lpath.is_file():
        labels = (read_yaml(lpath) or {}).get("labels", []) or []
        gaz = load_gazetteer()
        for lb in labels:
            if not lb.get("point") or not lb.get("place"):
                continue
            loc = (gaz.get(lb["place"]) or {}).get("location") or {}
            if loc.get("precision") == "surveyed" and loc.get("lat") is not None and loc.get("lon") is not None:
                pts.append({"id": "mk-" + lb["id"], "x": lb["point"][0], "y": lb["point"][1],
                            "lon": loc["lon"], "lat": loc["lat"], "from": "marks"})
    need = 3 if order == 1 else 6
    if len(pts) < need:
        die(f"{len(pts)} control points; order {order} needs at least {need}")

    lon0 = float(np.mean([p["lon"] for p in pts]))
    lat0 = float(np.mean([p["lat"] for p in pts]))
    kx, ky = math.cos(math.radians(lat0)) * 111320.0, 110540.0
    src = np.array([[p["x"], p["y"]] for p in pts], float)
    dst = np.array([[(p["lon"] - lon0) * kx, (p["lat"] - lat0) * ky] for p in pts], float)

    coef = fit(src, dst, order)
    res = np.hypot(*(apply(coef, src, order) - dst).T)
    rms = float(math.sqrt(np.mean(res ** 2)))
    inv = fit(dst, src, order)
    inv_res = np.hypot(*(apply(inv, dst, order) - src).T)
    inv_rms = float(math.sqrt(np.mean(inv_res ** 2)))

    print(f"{len(pts)} control points, order {order}")
    for p, r in zip(pts, res):
        flag = "  <-- over 3 x RMS: a possible misidentification" if rms > 0 and r > 3 * rms else ""
        print(f"  {p['id']:>14}  {r:8.2f} m{flag}")
    print(f"RMS {rms:.2f} m (inverse fit RMS {inv_rms:.1f} px)")

    geo["fit"] = {"transformation": "polynomial", "order": order, "n": len(pts),
                  "rms_m": round(rms, 2), "inverse_rms_px": round(inv_rms, 1),
                  "residuals_m": {p["id"]: round(float(r), 2) for p, r in zip(pts, res)}}
    dump_yaml(gpath, geo, header_of(gpath))

    if labels:
        positions = []
        for lb in labels:
            if not lb.get("point"):
                continue
            ll = apply(coef, np.array(lb["point"], float), order)[0]
            positions.append({"label": lb["id"], "place": lb.get("place"),
                              "lon": round(float(lon0 + ll[0] / kx), 6), "lat": round(float(lat0 + ll[1] / ky), 6)})
        dump_yaml(map_dir(key) / "positions.yml", {"rms_m": round(rms, 2), "positions": positions},
                  POSITIONS_HEADER.format(key=key))
        print(f"{len(positions)} positions -> maps/{key}/positions.yml")

    crop = m.get("crop")
    dx, dy = (crop[0], crop[1]) if crop else (0, 0)
    W, H = (crop[2], crop[3]) if crop else (m["width"], m["height"])
    feats = [{"type": "Feature",
              "properties": {"resourceCoords": [round(p["x"] - dx), round(p["y"] - dy)]},
              "geometry": {"type": "Point", "coordinates": [p["lon"], p["lat"]]}} for p in pts]
    ann = {"@context": ["http://iiif.io/api/extension/georef/1/context.json",
                        "http://iiif.io/api/presentation/3/context.json"],
           "type": "Annotation", "motivation": "georeferencing",
           "target": {"type": "SpecificResource",
                      "source": {"id": TILE_BASE + "/" + key, "type": "ImageService3",
                                 "profile": "level0", "width": W, "height": H},
                      "selector": {"type": "SvgSelector",
                                   "value": f'<svg width="{W}" height="{H}"><polygon points="0,0 {W},0 {W},{H} 0,{H}" /></svg>'}},
           "body": {"type": "FeatureCollection",
                    "transformation": {"type": "polynomial", "options": {"order": order}},
                    "features": feats}}
    out = MAPS_REPO / key
    out.mkdir(parents=True, exist_ok=True)
    with open(out / "georef.json", "w", encoding="utf-8", newline="\n") as f:
        json.dump(ann, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"annotation -> {out / 'georef.json'}")


main()
