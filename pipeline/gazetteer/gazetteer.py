#!/usr/bin/env python3
"""The gazetteer: loader, checker and the missing-sources list.

The gazetteer is reference/gazetteer/<slug>.yml, one file per place, made once
from the editor's "Place Names.md" by import_place_names.py and edited by hand
since. This module loads them and does two jobs:

    python pipeline/gazetteer/gazetteer.py --check
        checks every file: footnote markers and footnote items agree, every
        source key exists in reference/gazetteer_sources.yml, every link
        resolves inside the edition (documents and their pages in
        corpus/letters.json, literature pages in corpus/literature/, the
        glossary), every map key is in reference/maps.yml, every register
        slug is in reference/places.yml, every place named in a location
        exists. Exits 1 on any failure; prints counts.

    python pipeline/gazetteer/gazetteer.py --missing
        rewrites the generated block of docs/MISSING_SOURCES.md (between its
        BEGIN and END marker lines) from the footnotes that cite sources not
        yet in the edition and from the maps. Nothing else in that file is
        touched.
"""
import glob
import io
import json
import os
import re
import sys
from collections import OrderedDict

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
GAZ = os.path.join(ROOT, 'reference', 'gazetteer')
MISSING_MD = os.path.join(ROOT, 'docs', 'MISSING_SOURCES.md')
BEGIN = '<!-- BEGIN generated by pipeline/gazetteer/gazetteer.py --missing: do not edit by hand -->'
END = '<!-- END generated -->'


def _yaml(*parts):
    with open(os.path.join(ROOT, *parts), encoding='utf-8') as f:
        return yaml.safe_load(f)


def load_places():
    """slug -> data, for every reference/gazetteer/*.yml (not source/)."""
    out = OrderedDict()
    for path in sorted(glob.glob(os.path.join(GAZ, '*.yml'))):
        with open(path, encoding='utf-8') as f:
            d = yaml.safe_load(f)
        d['_file'] = os.path.basename(path)
        out[d.get('slug', os.path.basename(path)[:-4])] = d
    return out


def check():
    places = load_places()
    sources = _yaml('reference', 'gazetteer_sources.yml')['sources']
    maps = _yaml('reference', 'maps.yml')['maps']
    reg = _yaml('reference', 'places.yml')['places']
    glossary = _yaml('reference', 'glossary.yml')
    gl_ids = {e['id'] for e in (glossary['entries'] if isinstance(glossary, dict) and 'entries' in glossary else glossary)}
    with open(os.path.join(ROOT, 'corpus', 'letters.json'), encoding='utf-8') as f:
        docs = {d['permalink']: len(d['pages']) for d in json.load(f)}
    errors = []
    slugs = set()
    counts = dict(entries=0, footnotes=0, linked=0, missing=0, maps=0, review=0)

    def err(slug, msg):
        errors.append('%s: %s' % (slug, msg))

    def check_link(slug, link):
        if link.startswith(('http://', 'https://')):
            return
        m = re.match(r'^(/documents/[^/]+/\d+/)(?:#p(\d+))?$', link)
        if m:
            if m.group(1) not in docs:
                err(slug, 'link %s: no such document' % link)
            elif m.group(2) and not 1 <= int(m.group(2)) <= docs[m.group(1)]:
                err(slug, 'link %s: page out of range (%d pages)' % (link, docs[m.group(1)]))
            return
        m = re.match(r'^/literature/([^/]+)/#p-(\w+)$', link)
        if m:
            if not glob.glob(os.path.join(ROOT, 'corpus', 'literature', m.group(1), m.group(2) + '.*.txt')):
                err(slug, 'link %s: no such page in corpus/literature' % link)
            return
        m = re.match(r'^/literature/([^/]+)/$', link)
        if m:
            if not os.path.isdir(os.path.join(ROOT, 'literature', m.group(1))):
                err(slug, 'link %s: no such work folder' % link)
            return
        m = re.match(r'^/glossary/#(.+)$', link)
        if m:
            if m.group(1) not in gl_ids:
                err(slug, 'link %s: no such glossary entry' % link)
            return
        err(slug, 'link %s: not a form the checker knows' % link)

    for slug, d in places.items():
        counts['entries'] += 1
        if slug in slugs:
            err(slug, 'duplicate slug')
        slugs.add(slug)
        if d['_file'] != slug + '.yml':
            err(slug, 'file name %s does not match the slug' % d['_file'])
        text = d.get('text_en') or ''
        markers = [int(x) for x in re.findall(r'\[\^(\d+)\]', text)]
        items = [f['n'] for f in d.get('footnotes') or []]
        for n in sorted(set(markers) - set(items)):
            err(slug, 'marker [^%d] has no footnote item' % n)
        for n in sorted(set(items) - set(markers)):
            err(slug, 'footnote item %d has no marker in text_en' % n)
        for f in d.get('footnotes') or []:
            counts['footnotes'] += 1
            for r in f.get('refs') or []:
                st = r.get('status')
                if r.get('source') is None:
                    if st != 'missing':
                        err(slug, 'fn %s: no source but status %s' % (f['n'], st))
                elif r['source'] not in sources:
                    err(slug, 'fn %s: unknown source key %s' % (f['n'], r['source']))
                if st == 'linked':
                    counts['linked'] += 1
                    if not r.get('link'):
                        err(slug, 'fn %s: status linked with no link' % f['n'])
                elif st == 'missing':
                    counts['missing'] += 1
                    if r.get('link'):
                        err(slug, 'fn %s: status missing but has a link' % f['n'])
                else:
                    err(slug, 'fn %s: status %r' % (f['n'], st))
                if r.get('link'):
                    check_link(slug, r['link'])
        for m in d.get('maps') or []:
            counts['maps'] += 1
            if m.get('map') not in maps:
                err(slug, 'unknown map key %s' % m.get('map'))
        if d.get('register') is not None and d['register'] not in reg:
            err(slug, 'register slug %s is not in reference/places.yml' % d['register'])
        counts['review'] += len(d.get('review') or [])
    for slug, d in places.items():
        loc = d.get('location') or {}
        for k in ('relative_to', 'belongs_to'):
            if loc.get(k) is not None and loc[k] not in places:
                err(slug, 'location.%s %s is not a gazetteer slug' % (k, loc[k]))
    for e in errors:
        print('FAIL', e)
    print('entries %(entries)d, footnotes %(footnotes)d, refs linked %(linked)d / missing %(missing)d, '
          'map appearances %(maps)d, review notes %(review)d' % counts)
    print('%d failure(s)' % len(errors) if errors else 'ALL CHECKS PASSED')
    return 1 if errors else 0


def _year_of_footnote(d, n):
    text = d.get('text_en') or ''
    i = text.find('[^%d]' % n)
    if i < 0:
        return None
    start = 0
    for m in re.finditer(r'[.;](?:\[\^\d+\])*\s+(?=\S)', text[:i]):
        start = m.end()
    sent = text[start:i]
    m = re.search(r'\b(1\d{3})\b', sent)
    return m.group(1) if m else None


def missing_block():
    places = load_places()
    sources = _yaml('reference', 'gazetteer_sources.yml')['sources']
    maps = _yaml('reference', 'maps.yml')['maps']
    by_src = OrderedDict()
    unmapped = []
    for slug, d in places.items():
        for f in d.get('footnotes') or []:
            for r in f.get('refs') or []:
                if r.get('status') != 'missing':
                    continue
                if r.get('source') is None:
                    unmapped.append((d['heading'], f['n'], f.get('text')))
                    continue
                loc = r.get('locator') or ''
                if r['source'] == 'kdw':
                    y = _year_of_footnote(d, f['n'])
                    if y:
                        loc = '%s (%s)' % (loc, y)
                by_src.setdefault(r['source'], OrderedDict()).setdefault(loc, [])
                if d['heading'] not in by_src[r['source']][loc]:
                    by_src[r['source']][loc].append(d['heading'])
    order = {'archive': 0, 'edition': 1, 'register': 2, 'dictionary': 3}
    keys = sorted(by_src, key=lambda k: (order.get(sources[k].get('kind'), 4), ' '.join(sources[k]['cite'].split())))

    def nk(loc):
        m = re.match(r'vol\. (\d+), no\. (\d+)', loc)
        if m:
            return (0, int(m.group(1)), int(m.group(2)), loc)
        m = re.search(r'(\d+)', loc)
        return (1, int(m.group(1)) if m else 0, 0, loc)

    L = ['## Cited by the gazetteer', '']
    for k in keys:
        s = sources[k]
        L.append('### ' + ' '.join(s['cite'].split()))
        L.append('')
        if s.get('in_project'):
            L.append('In the edition: %s' % ' '.join(str(s['in_project']).split()))
            L.append('')
        if s.get('wanted'):
            L.append('Wanted: %s' % ' '.join(str(s['wanted']).split()))
            L.append('')
        for loc in sorted(by_src[k], key=nk):
            L.append('- %s - %s' % (loc or '(the work as a whole)', ', '.join(by_src[k][loc])))
        L.append('')
    if unmapped:
        L.append('### Footnotes not mapped to a source')
        L.append('')
        for h, n, t in unmapped:
            L.append('- %s, note %s: %s' % (h, n, t))
        L.append('')
    L.append('## Maps')
    L.append('')
    L.append('None of the maps is in the edition yet. Their full descriptions (title, maker, '
             'holder, reference) are still to be filled in `reference/maps.yml`.')
    L.append('')
    L.append('| Map | Places citing it | Headings |')
    L.append('|---|---|---|')
    use = {}
    for slug, d in places.items():
        for m in d.get('maps') or []:
            use.setdefault(m['map'], [])
            if d['heading'] not in use[m['map']]:
                use[m['map']].append(d['heading'])
    for mk, mv in sorted(maps.items(), key=lambda kv: (kv[1].get('year') or 0, kv[1]['cited_as'])):
        if mv.get('in_project'):
            continue
        hs = use.get(mk, [])
        L.append('| %s | %d | %s |' % (mv['cited_as'], len(hs), ', '.join(hs)))
    return '\n'.join(L).rstrip() + '\n'


def write_missing():
    with open(MISSING_MD, encoding='utf-8', newline='') as f:
        md = f.read().replace('\r\n', '\n')
    a, b = md.find(BEGIN), md.find(END)
    if a < 0 or b < 0 or b < a:
        print('markers not found in docs/MISSING_SOURCES.md')
        return 1
    new = md[:a + len(BEGIN)] + '\n\n' + missing_block() + '\n' + md[b:]
    with open(MISSING_MD, 'w', encoding='utf-8', newline='\n') as f:
        f.write(new)
    print('docs/MISSING_SOURCES.md: generated block rewritten')
    return 0


if __name__ == '__main__':
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
    if '--check' in sys.argv:
        sys.exit(check())
    if '--missing' in sys.argv:
        sys.exit(write_missing())
    print(__doc__)
    sys.exit(2)
