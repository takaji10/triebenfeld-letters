# -*- coding: utf-8 -*-
"""
The connections between documents of different holdings: reference/connections.yml
into site/_data/connections.yml, keyed by document.

Reads  : reference/connections.yml (docs/CONNECTIONS.md), dataset/letters.json,
         units/<slug>/unit.yml (the holding's ref)
Writes : site/_data/connections.yml  the connections, by document (letter.html:
         each participant's page shows its own note and links to the others)

A connection names at least two documents, each with its own note in English
and German — the note THAT document's page shows, so that no page carries a
sentence written for the other side (the per-passage lesson of the literature's
links, docs/LITERATURE_PLAN.md section 32). The script stops on a connection
with fewer than two documents, on a document that does not exist, on a note
with no en or de, and on a uid named twice in one connection.

Everything under site/_data/connections.yml is generated output.

Usage: python pipeline/build/connections_site.py
"""
import io, os, re, sys, json, html
import yaml

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'reference', 'connections.yml')
OUT = os.path.join(ROOT, 'site', '_data', 'connections.yml')

MONTHS = {1: 'January', 2: 'February', 3: 'March', 4: 'April', 5: 'May', 6: 'June',
          7: 'July', 8: 'August', 9: 'September', 10: 'October', 11: 'November',
          12: 'December'}
MONTHS_DE = {1: 'Januar', 2: 'Februar', 3: 'März', 4: 'April', 5: 'Mai', 6: 'Juni',
             7: 'Juli', 8: 'August', 9: 'September', 10: 'Oktober',
             11: 'November', 12: 'Dezember'}


def doc_date(r, lang):
    """The date as the document's own page gives it (build_site_data.date_label)."""
    if not r['date_iso']:
        return 'undatiert' if lang == 'de' else 'undated'
    y, m, d = r['year'], r['month'], r['day']
    months = MONTHS_DE if lang == 'de' else MONTHS
    if d:
        return f"{d}. {months[m]} {y}" if lang == 'de' else f"{d} {months[m]} {y}"
    return f"{months[m]} {y}" if m else str(y)


def main():
    with open(SRC, encoding='utf-8') as f:
        connections = yaml.safe_load(f) or []
    with open(os.path.join(ROOT, 'dataset', 'letters.json'), encoding='utf-8') as f:
        letters = {r['uid']: r for r in json.load(f)}
    refs, errors = {}, []
    for cn in connections:
        cid = cn.get('id', '?')
        docs = cn.get('documents') or []
        if len(docs) < 2:
            errors.append(f'{cid}: a connection names at least two documents')
        seen = set()
        for d in docs:
            uid = d.get('uid')
            if not uid:
                errors.append(f'{cid}: a participant without a uid')
                continue
            if uid in seen:
                errors.append(f'{cid}: {uid} named twice')
            seen.add(uid)
            r = letters.get(uid)
            if not r:
                errors.append(f'{cid}: no document {uid}')
                continue
            for lg in ('en', 'de'):
                if not d.get(lg):
                    errors.append(f'{cid}: {uid} has no {lg}')
            if r['unit'] not in refs:
                with open(os.path.join(ROOT, 'units', r['unit'], 'unit.yml'),
                          encoding='utf-8') as f:
                    refs[r['unit']] = yaml.safe_load(f)['ref']
    if errors:
        sys.exit('reference/connections.yml:\n  ' + '\n  '.join(errors))

    per_doc = {}
    with open(os.path.join(ROOT, 'site', '_data', 'i18n.yml'), encoding='utf-8') as f:
        strings = yaml.safe_load(f)
    for cn in connections:
        parts = [(d['uid'], d) for d in cn['documents']]
        for uid, d in parts:
            r = letters[uid]
            others = []
            for ouid, od in parts:
                if ouid == uid:
                    continue
                o = letters[ouid]
                ref = refs[o['unit']]
                others.append({
                    'uid': ouid,
                    'permalink': o['permalink'],
                    'label_en': strings['en']['lit_doc'] % (ref, o['letter_id'])
                                + f' ({doc_date(o, "en")})',
                    'label_de': strings['de']['lit_doc'] % (ref, o['letter_id'])
                                + f' ({doc_date(o, "de")})',
                })
            per_doc.setdefault(uid, []).append(
                {'id': cn['id'], 'en': d['en'], 'de': d['de'], 'others': others})

    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# Generated by pipeline/build/connections_site.py from\n'
                '# reference/connections.yml: the connections between documents\n'
                '# of different holdings, keyed by document.\n')
        yaml.safe_dump(per_doc, f, allow_unicode=True, sort_keys=True, width=1000)
    print(f'{len(connections)} cross-holding connections: '
          f'{len(per_doc)} documents carry an entry')


if __name__ == '__main__':
    main()
