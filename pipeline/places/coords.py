# -*- coding: utf-8 -*-
"""
Coordinates for every place of the Places page (docs/PLACES_PEOPLE_GLOSSARY_PLAN.md,
step A1).

A place's position comes from its gazetteer entry (`location:` in
reference/gazetteer/<slug>.yml), else from reference/place_coords.yml (Wikidata,
OpenStreetMap or a hand placing), else from reference/places_osm.yml (keyed by
the printed name, checked 2026-10-02); a historical place the gazetteer only
describes as lying near another is given that place's position, marked
approximate. A place with no sure position must be named
in reference/place_coords_unplaced.yml with the reason, so that a place added
to the register is never left out silently.

    python pipeline/places/coords.py           # write site/_data/place_coords.yml
    python pipeline/places/coords.py --check   # fail if a place is unaccounted for
                                                # or the data file is stale

Run after build_site_data.py (it reads site/_data/places_index.yml).
"""
import glob
import io
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'site', '_data', 'place_coords.yml')


def _load(p):
    if not os.path.isfile(p):
        return {}
    with open(p, encoding='utf-8') as f:
        return yaml.safe_load(f) or {}


def build():
    idx = _load(os.path.join(ROOT, 'site', '_data', 'places_index.yml'))
    stubs = _load(os.path.join(ROOT, 'reference', 'place_coords.yml'))
    osm = _load(os.path.join(ROOT, 'reference', 'places_osm.yml'))
    unplaced = _load(os.path.join(ROOT, 'reference', 'place_coords_unplaced.yml'))
    gaz, rel = {}, {}
    for p in glob.glob(os.path.join(ROOT, 'reference', 'gazetteer', '*.yml')):
        g = _load(p)
        gs = os.path.basename(p)[:-4]
        loc = g.get('location') or {}
        if loc.get('lat') and loc.get('lon'):
            gaz[gs] = (loc['lat'], loc['lon'])
            if g.get('register'):
                gaz.setdefault(g['register'], (loc['lat'], loc['lon']))
        elif loc.get('relative_to'):
            # the editor's described position ("north of Łukom"): within a
            # few kilometres of the place named, good enough for a distance
            # search, not for a marker of its own
            rel[gs] = loc['relative_to']
    # `at:` in place_coords.yml: a place that stood where another stands now
    # (Trąbczyńskie Stare Olędry at Łazińsk Pierwszy) takes its position
    for s, v in stubs.items():
        if isinstance(v, dict) and v.get('at') and v['at'] in gaz:
            gaz[s] = gaz[v['at']]
    out, missing = {}, []
    for tier in ('tier1', 'tier2'):
        for r in idx.get(tier) or []:
            if r.get('see') or r.get('sees'):
                continue
            s = r['slug']
            if s in gaz:
                lat, lon = gaz[s]
            elif s in stubs and stubs[s].get('lat') is not None:
                lat, lon = stubs[s]['lat'], stubs[s]['lon']
            elif r['name'] in osm and osm[r['name']].get('lat') is not None:
                lat, lon = osm[r['name']]['lat'], osm[r['name']]['lon']
            elif s in rel and (rel[s] in gaz or rel[s] in stubs):
                ref = gaz.get(rel[s]) or (stubs[rel[s]]['lat'], stubs[rel[s]]['lon'])
                out[s] = [round(float(ref[0]), 5), round(float(ref[1]), 5), 'near ' + rel[s]]
                continue
            else:
                if s not in unplaced:
                    missing.append(f"{s} ({r['name']}, {r.get('kind_en') or 'no kind'})")
                continue
            out[s] = [round(float(lat), 5), round(float(lon), 5)]
    stale_unplaced = sorted(set(unplaced) & set(out))
    text = ('# Generated by pipeline/places/coords.py - do not hand-edit.\n'
            '# slug: [lat, lon] for every place with a sure position; [lat, lon,\n'
            '# "near <slug>"] for a place the gazetteer describes only as lying\n'
            '# near another (approximate: for the distance search, not the map).\n'
            + yaml.safe_dump(dict(sorted(out.items())), default_flow_style=None,
                             allow_unicode=True, width=200))
    return text, missing, stale_unplaced


def main(argv):
    text, missing, stale = build()
    bad = False
    if missing:
        bad = True
        print(f'{len(missing)} place(s) with no position and no entry in '
              'reference/place_coords_unplaced.yml:')
        for m in missing:
            print('  ' + m)
    if stale:
        bad = True
        print('placed now, but still listed as unplaced: ' + ', '.join(stale))
    if '--check' in argv:
        cur = open(OUT, encoding='utf-8').read() if os.path.isfile(OUT) else ''
        if cur != text:
            bad = True
            print('site/_data/place_coords.yml is stale: run pipeline/places/coords.py')
        if not bad:
            print(f'coords: {text.count(chr(10)) - 2} places placed, the rest accounted for')
        return 1 if bad else 0
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(f'wrote {OUT} ({text.count(chr(10)) - 2} places)')
    return 1 if bad else 0


if __name__ == '__main__':
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
    sys.exit(main(sys.argv[1:]))
